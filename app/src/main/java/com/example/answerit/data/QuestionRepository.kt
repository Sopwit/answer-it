    fun getQuestions(language: Language = Language.TURKISH): List<Question> {
        return questionData.map { data ->
            Question(
                data.id,
                getQuestionText(data, language),
                getAnswerOptions(data, language),
                data.correctAnswer,
                data.difficulty,
                data.prizeMoney
            )
        }
    }

    fun getQuestion(index: Int, language: Language = Language.TURKISH): Question? {
        return if (index < questionData.size) {
            val data = questionData[index]
            Question(
                data.id,
                getQuestionText(data, language),
                getAnswerOptions(data, language),
                data.correctAnswer,
                data.difficulty,
                data.prizeMoney
            )
        } else null
    }

    private fun getQuestionText(data: QuestionData, language: Language): String {
        return when (language) {
            Language.TURKISH -> data.questionTurkish
            Language.ENGLISH -> data.questionEnglish
            Language.CHINESE -> data.questionChinese
            Language.SPANISH -> data.questionSpanish
            Language.ARABIC -> data.questionArabic
            Language.GERMAN -> data.questionGerman
            Language.FRENCH -> data.questionFrench
            Language.RUSSIAN -> data.questionRussian
            Language.HINDI -> data.questionHindi
            Language.JAPANESE -> data.questionJapanese
            Language.KOREAN -> data.questionKorean
            Language.PORTUGUESE -> data.questionPortuguese
            Language.VIETNAMESE -> data.questionVietnamese
            Language.ITALIAN -> data.questionItalian
        }
    }

    private fun getAnswerOptions(data: QuestionData, language: Language): List<String> {
